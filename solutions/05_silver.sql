-- Silver: Sales Transactions — unpivot wide regional columns into normalized rows
-- TARGET_LAG = 'DOWNSTREAM': only refresh when a Gold table needs this data
-- clean DDL - CATALOG and EXTERNAL_VOLUME are set at the database RETAIL_HOL_ICEBERG

CREATE OR REPLACE DYNAMIC ICEBERG TABLE SILVER_MANAGED_ICEBERG.SILVER_SALES
  TARGET_LAG = 'DOWNSTREAM'
  WAREHOUSE = RETAIL_HOL_WH
  REFRESH_MODE = ADAPTIVE
AS
  SELECT ID AS TRANSACTION_ID, PRODUCT_NAME, TRANSACTION_DATE,
         'ONLINE' AS REGION, UNITS_ONLINE AS UNITS_SOLD,
         (UNITS_ONLINE + UNITS_NE + UNITS_NW + UNITS_SE + UNITS_SW) AS TOTAL_UNITS,
         CREATED_AT
  FROM BRONZE.SALES_TRANSACTIONS
  UNION ALL
  SELECT ID, PRODUCT_NAME, TRANSACTION_DATE,
         'NORTHEAST', UNITS_NE,
         (UNITS_ONLINE + UNITS_NE + UNITS_NW + UNITS_SE + UNITS_SW),
         CREATED_AT
  FROM BRONZE.SALES_TRANSACTIONS
  UNION ALL
  SELECT ID, PRODUCT_NAME, TRANSACTION_DATE,
         'NORTHWEST', UNITS_NW,
         (UNITS_ONLINE + UNITS_NE + UNITS_NW + UNITS_SE + UNITS_SW),
         CREATED_AT
  FROM BRONZE.SALES_TRANSACTIONS
  UNION ALL
  SELECT ID, PRODUCT_NAME, TRANSACTION_DATE,
         'SOUTHEAST', UNITS_SE,
         (UNITS_ONLINE + UNITS_NE + UNITS_NW + UNITS_SE + UNITS_SW),
         CREATED_AT
  FROM BRONZE.SALES_TRANSACTIONS
  UNION ALL
  SELECT ID, PRODUCT_NAME, TRANSACTION_DATE,
         'SOUTHWEST', UNITS_SW,
         (UNITS_ONLINE + UNITS_NE + UNITS_NW + UNITS_SE + UNITS_SW),
         CREATED_AT
  FROM BRONZE.SALES_TRANSACTIONS;

-- silver_inventory
-- Silver: Inventory Feed — flatten JSON, classify stock health, extract geolocation
-- clean DDL - CATALOG and EXTERNAL_VOLUME are set at the database RETAIL_HOL_ICEBERG
CREATE OR REPLACE DYNAMIC ICEBERG TABLE SILVER_MANAGED_ICEBERG.SILVER_INVENTORY
  TARGET_LAG = '5 minutes'
  WAREHOUSE = RETAIL_HOL_WH
  REFRESH_MODE = ADAPTIVE
AS
  SELECT
    ID AS INVENTORY_ID,
    SKU_NAME,
    SNAPSHOT_DATE,
    QTY_ONLINE,
    QTY_NORTHEAST,
    QTY_SOUTHEAST,
    QTY_SOUTHWEST,
    QTY_NORTHWEST,
    (QTY_ONLINE + QTY_NORTHEAST + QTY_SOUTHEAST + QTY_SOUTHWEST + QTY_NORTHWEST) AS TOTAL_STOCK,
    METADATA:supplier::VARCHAR AS SUPPLIER,
    METADATA:quality_score::FLOAT AS QUALITY_SCORE,
    METADATA:storage_temp_f::INT AS STORAGE_TEMP_F,
    METADATA:batch_id::VARCHAR AS BATCH_ID,
    METADATA:last_audit::DATE AS LAST_AUDIT_DATE,
    CASE
      WHEN (QTY_ONLINE + QTY_NORTHEAST + QTY_SOUTHEAST + QTY_SOUTHWEST + QTY_NORTHWEST) < 50000 THEN 'CRITICAL'
      WHEN (QTY_ONLINE + QTY_NORTHEAST + QTY_SOUTHEAST + QTY_SOUTHWEST + QTY_NORTHWEST) < 100000 THEN 'LOW'
      WHEN (QTY_ONLINE + QTY_NORTHEAST + QTY_SOUTHEAST + QTY_SOUTHWEST + QTY_NORTHWEST) < 200000 THEN 'NORMAL'
      ELSE 'OVERSTOCKED'
    END AS STOCK_HEALTH,
    ST_X(TO_GEOMETRY(WAREHOUSE_LOCATION)) AS WAREHOUSE_LONGITUDE,
    ST_Y(TO_GEOMETRY(WAREHOUSE_LOCATION)) AS WAREHOUSE_LATITUDE,
    CREATED_AT
  FROM BRONZE.INVENTORY_FEED;

-- silver_reviews
-- Silver: Product Reviews — Cortex AI sentiment scoring + theme classification
-- Every new review gets AI-enriched automatically on refresh
-- clean DDL - CATALOG and EXTERNAL_VOLUME are set at the database RETAIL_HOL_ICEBERG
CREATE OR REPLACE DYNAMIC ICEBERG TABLE SILVER_MANAGED_ICEBERG.SILVER_PRODUCT_REVIEWS
  TARGET_LAG = '10 minutes'
  WAREHOUSE = RETAIL_HOL_WH
  REFRESH_MODE = ADAPTIVE
AS
  SELECT
    ID AS REVIEW_ID,
    PRODUCT_ID,
    PRODUCT_NAME,
    TITLE AS REVIEW_TITLE,
    BODY AS REVIEW_BODY,
    STAR_RATING,
    AUTHOR,
    SUBMITTED_AT,
    IS_VERIFIED,
    HELPFUL_VOTES,
    MODERATION_STATUS,
    API_SOURCE AS CHANNEL,
    SNOWFLAKE.CORTEX.SENTIMENT(BODY) AS AI_SENTIMENT_SCORE,
    SNOWFLAKE.CORTEX.CLASSIFY_TEXT(
      BODY,
      ['product_quality', 'shipping_packaging', 'scent_fragrance', 'value_for_money', 'customer_service']
    ):label::VARCHAR AS AI_REVIEW_THEME,
    CREATED_AT
  FROM BRONZE.PRODUCT_REVIEWS;

