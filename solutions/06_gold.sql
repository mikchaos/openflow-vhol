USE ROLE RETAIL_HOL_ROLE;
USE WAREHOUSE RETAIL_HOL_WH;
USE DATABASE RETAIL_HOL_ICEBERG;

-- gold_perf
-- Gold: Daily Product Performance — joins sales + inventory + sentiment
-- FROZEN WHERE: rows older than 7 days are immutable, skip refresh entirely
-- clean DDL - CATALOG and EXTERNAL_VOLUME are set at the database RETAIL_HOL_ICEBERG
CREATE OR REPLACE DYNAMIC ICEBERG TABLE GOLD_MANAGED_ICEBERG.DAILY_PRODUCT_PERFORMANCE
  TARGET_LAG = '10 minutes'
  WAREHOUSE = RETAIL_HOL_WH
  REFRESH_MODE = ADAPTIVE
  FROZEN WHERE (PERFORMANCE_DATE < CURRENT_DATE() - INTERVAL '7 days')
AS
  SELECT
    s.TRANSACTION_DATE AS PERFORMANCE_DATE,
    s.PRODUCT_NAME,
    SUM(s.TOTAL_UNITS) AS TOTAL_UNITS_SOLD,
    SUM(CASE WHEN s.REGION = 'ONLINE' THEN s.UNITS_SOLD ELSE 0 END) AS ONLINE_UNITS,
    SUM(CASE WHEN s.REGION != 'ONLINE' THEN s.UNITS_SOLD ELSE 0 END) AS STORE_UNITS,
    MAX(i.TOTAL_STOCK) AS INVENTORY_POSITION,
    MAX(i.STOCK_HEALTH) AS STOCK_HEALTH_STATUS,
    MAX(i.QUALITY_SCORE) AS QUALITY_SCORE,
    AVG(r.SENTIMENT_SUM) AS AVG_DAILY_SENTIMENT,
    SUM(r.POSITIVE_COUNT) AS POSITIVE_REVIEWS,
    SUM(r.NEGATIVE_COUNT) AS NEGATIVE_REVIEWS
  FROM SILVER_MANAGED_ICEBERG.SILVER_SALES s
  LEFT JOIN SILVER_MANAGED_ICEBERG.SILVER_INVENTORY i
    ON s.PRODUCT_NAME = i.SKU_NAME
    AND i.SNAPSHOT_DATE = DATE_TRUNC('WEEK', s.TRANSACTION_DATE)
  LEFT JOIN BRONZE.DAILY_REVIEWS r
    ON s.PRODUCT_NAME = r.PRODUCT
    AND s.TRANSACTION_DATE = r.REVIEW_DATE
  GROUP BY 1, 2;

-- gold_voice
-- Gold: Customer Voice Analytics — full Cortex AI enrichment pipeline
-- SENTIMENT + SUMMARIZE + CLASSIFY_TEXT — all inline, all automatic
-- Frozen region: comments older than 14 days never re-processed
-- clean DDL - CATALOG and EXTERNAL_VOLUME are set at the database RETAIL_HOL_ICEBERG

CREATE OR REPLACE DYNAMIC ICEBERG TABLE GOLD_MANAGED_ICEBERG.CUSTOMER_VOICE_ANALYTICS
  TARGET_LAG = '15 minutes'
  WAREHOUSE = RETAIL_HOL_WH
  REFRESH_MODE = ADAPTIVE
  FROZEN WHERE (COMMENT_DATE < CURRENT_DATE() - INTERVAL '14 days')
AS
  SELECT
    c.ID AS COMMENT_ID,
    c.ITEM_NAME AS PRODUCT_NAME,
    c.COMMENT_TITLE,
    c.COMMENT_BODY,
    c.USER_NAME,
    c.CREATED_AT::DATE AS COMMENT_DATE,
    c.CHANNEL,
    SNOWFLAKE.CORTEX.SENTIMENT(c.COMMENT_BODY) AS SENTIMENT_SCORE,
    SNOWFLAKE.CORTEX.SUMMARIZE(c.COMMENT_BODY) AS AI_SUMMARY,
    SNOWFLAKE.CORTEX.CLASSIFY_TEXT(
      c.COMMENT_BODY,
      ['praise', 'complaint', 'question', 'suggestion', 'shipping_issue']
    ):label::VARCHAR AS CUSTOMER_INTENT,
    c.CREATED_AT
  FROM BRONZE.CUSTOMER_COMMENTS c;

-- gold_scorecard
-- Gold: Weekly Product Scorecard — executive rollup
-- Reads from another DT (DAILY_PRODUCT_PERFORMANCE) — chained pipeline!
-- Frozen 30 days = only refresh current month
-- clean DDL - CATALOG and EXTERNAL_VOLUME are set at the database RETAIL_HOL_ICEBERG
CREATE OR REPLACE DYNAMIC ICEBERG TABLE GOLD_MANAGED_ICEBERG.WEEKLY_PRODUCT_SCORECARD
  TARGET_LAG = '1 hour'
  WAREHOUSE = RETAIL_HOL_WH
  REFRESH_MODE = ADAPTIVE
  FROZEN WHERE (WEEK_START < CURRENT_DATE() - INTERVAL '30 days')
AS
  SELECT
    DATE_TRUNC('WEEK', PERFORMANCE_DATE)::DATE AS WEEK_START,
    PRODUCT_NAME,
    SUM(TOTAL_UNITS_SOLD) AS WEEKLY_UNITS_SOLD,
    SUM(ONLINE_UNITS) AS WEEKLY_ONLINE_UNITS,
    SUM(STORE_UNITS) AS WEEKLY_STORE_UNITS,
    ROUND(SUM(ONLINE_UNITS) * 100.0 / NULLIF(SUM(TOTAL_UNITS_SOLD), 0), 1) AS ONLINE_MIX_PCT,
    AVG(INVENTORY_POSITION) AS AVG_INVENTORY,
    MAX(STOCK_HEALTH_STATUS) AS WORST_STOCK_STATUS,
    AVG(QUALITY_SCORE) AS AVG_QUALITY_SCORE,
    AVG(AVG_DAILY_SENTIMENT) AS WEEKLY_SENTIMENT,
    SUM(POSITIVE_REVIEWS) AS WEEKLY_POSITIVE,
    SUM(NEGATIVE_REVIEWS) AS WEEKLY_NEGATIVE,
    ROUND(SUM(POSITIVE_REVIEWS) * 100.0 /
      NULLIF(SUM(POSITIVE_REVIEWS) + SUM(NEGATIVE_REVIEWS), 0), 1) AS POSITIVE_REVIEW_PCT
  FROM GOLD_MANAGED_ICEBERG.DAILY_PRODUCT_PERFORMANCE
  GROUP BY 1, 2;

-- Checkpoint G
-- refresh_hist
-- Check recent refresh activity to confirm the pipeline is running
SELECT
  NAME,
  STATE,
  REFRESH_TRIGGER,
  REFRESH_START_TIME,
  REFRESH_END_TIME,
  DATEDIFF('second', REFRESH_START_TIME, REFRESH_END_TIME) AS DURATION_SEC
FROM TABLE(INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY())
WHERE SCHEMA_NAME IN ('SILVER_MANAGED_ICEBERG', 'GOLD_MANAGED_ICEBERG')
ORDER BY REFRESH_START_TIME DESC
LIMIT 10;
